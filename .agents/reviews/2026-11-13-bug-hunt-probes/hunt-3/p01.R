source("common.R")
d <- tempfile("c"); s <- cache(d)
# fork: child opens fresh cache() while parent holds it open
j <- parallel::mcparallel({ tr({ s2 <- cache(d); cache_set(s2, "child", 1); cache_get(s2, "child") }) })
show("child fresh open w/ parent open", parallel::mccollect(j))
j <- parallel::mcparallel({ tr(cache_get(s, "x", default = NULL)) })
show("child inherited", parallel::mccollect(j))
j <- parallel::mcparallel({ tr(cache_close(s)) })
show("child close inherited", parallel::mccollect(j))
j <- parallel::mcparallel({ tr(cache_is_open(s)) })
show("child is_open inherited", parallel::mccollect(j))
show("parent after", tr({cache_set(s, "p", 1); cache_keys(s)}))
# design.md mclapply example
r <- parallel::mclapply(1:2, function(k) tr({ s3 <- cache(d); on.exit(cache_close(s3)); cache_get(s3, "p") }))
show("design example with parent open", r)
cache_close(s)
r <- parallel::mclapply(1:2, function(k) tr({ s3 <- cache(d); on.exit(cache_close(s3)); cache_set(s3, paste0("k", k), k); cache_get(s3, "p") }))
show("design example with parent closed", r)
s <- cache(d); show("keys", cache_keys(s)); show("check", tr(cache_check(s)))

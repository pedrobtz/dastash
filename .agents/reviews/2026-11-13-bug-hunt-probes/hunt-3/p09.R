source("common.R")
big <- function(i) as.raw(rep(i, 50000))
d <- tempfile("c"); s <- cache(d, timeout = 0); cache_set(s, "a", 1); cache_set(s, "blob", big(1))
flag <- tempfile("flag")
holder <- function(d, flag, hold, abort = FALSE) {
  library(dazcache); s <- cache(d)
  big <- function(i) as.raw(rep(i, 50000))
  try(cache_transact(s, { cache_set(s, "a", 2); cache_set(s, "h", big(2)); cache_delete(s, "blob"); file.create(flag); Sys.sleep(hold); if (abort) stop("abort") }))
  file.create(paste0(flag, ".done")); cache_close(s); "done"
}
wait_for <- function(f) while (!file.exists(f)) Sys.sleep(0.01)
# --- commit case
bg <- callr::r_bg(holder, list(d, flag, 2), libpath = LP); wait_for(flag); t0 <- Sys.time()
show("during: a", cache_get(s, "a")); show("during: count", cache_count(s)); show("during: blob", identical(cache_get(s, "blob"), big(1)))
show("during: has h", cache_has(s, "h")); show("during: files", files(d)); show("during: stats", tr(cache_stats(s)))
show("during: check", tr(cache_check(s)))
t <- system.time(r <- tr(cache_set(s, "w", 1)))[["elapsed"]]; show("timeout 0", list(r, t))
s1 <- cache(d, timeout = 0.5); t <- system.time(r <- tr(cache_set(s1, "w", 1)))[["elapsed"]]; show("timeout .5", list(r, t))
show("incr busy", tr(cache_incr(s, "n"))); show("delete busy", tr(cache_delete(s, "a"))); show("transact busy", tr(cache_transact(s, 1)))
show("evict busy", tr(cache_evict(s, prefix = "a"))); show("expire busy", tr(cache_expire(s))); show("cull busy", tr(cache_cull(s)));show("pop busy", tr(cache_pop(s, "a"))); show("clear busy", tr(cache_clear(s)))
show("open another handle while busy", tr({x <- cache(d); cache_close(x); "ok"}))
show("open in other proc while busy", tr(callr::r(function(d) { library(dazcache); t <- system.time(x <- cache(d, timeout = 0))[[3]]; r <- cache_get(x, "a"); c(r, t) }, list(d), libpath = LP)))
show("tmp during", list.files(file.path(d, "tmp")))
s3 <- cache(d, timeout = 5); t <- system.time(r <- tr({cache_set(s3, "w", 1); "ok"}))[["elapsed"]]; show("timeout 5", list(r, t, as.numeric(Sys.time() - t0)))
bg$wait(); show("after commit", list(cache_get(s, "a"), cache_keys(s), files(d), cache_check(s)))
# --- abort case
unlink(flag)
bg <- callr::r_bg(holder, list(d, flag, 0.5, TRUE), libpath = LP); wait_for(paste0(flag, ".done")); bg$wait()
show("after abort", list(cache_get(s, "a"), cache_keys(s), files(d), cache_check(s)))
# --- SIGKILL
unlink(c(flag, paste0(flag, ".done"))); cache_set(s, "blob", big(1))
bg <- callr::r_bg(holder, list(d, flag, 30), libpath = LP); wait_for(flag); tools::pskill(bg$get_pid(), tools::SIGKILL); bg$wait()
show("after kill: read", list(cache_get(s, "a"), cache_keys(s), identical(cache_get(s, "blob"), big(1)), files(d)))
show("after kill: check", tr(cache_check(s)))
show("after kill: write t0", tr({cache_set(s, "k", 1); "ok"}))
show("after kill: other proc write", tr(callr::r(function(d) { library(dazcache); x <- cache(d, timeout = 1); cache_set(x, "k2", 1); "ok" }, list(d), libpath = LP)))
cache_close(s); cache_close(s1); cache_close(s3); show("reg", ls(dazcache:::engine_registry))
s <- cache(d, timeout = 1)
show("after all closed: write", tr({cache_set(s, "k", 1); "ok"})); show("check", tr(cache_check(s))); show("files", files(d))
show("repair", tr(cache_check(s, repair = TRUE))); show("files", files(d)); show("keys", cache_keys(s))

source("lib.R")
p <- function(label, x) cat(sprintf("%-28s %s\n", label, substr(paste(capture.output(print(x)), collapse=" / "), 1, 400)))
s <- cache(tempfile("c-"))
cm <- as_cachem(s)
p("set/get", tr({cm$set("abc", 1:3); cm$get("abc")}))
p("miss", tr(class(cm$get("zz")))); p("is key_missing", tr(cachem::is.key_missing(cm$get("zz"))))
p("miss custom", tr(cm$get("zz", missing = NULL)))
p("miss stop", tr(cm$get("zz", missing = stop("Missing key"))))
p("bad key upper", tr(cm$set("ABC", 1))); p("bad key .", tr(cm$get("a.b"))); p("bad key vec", tr(cm$get(c("a","b")))); p("bad key newline", tr(cm$set("abc\n", 1))); p("empty", tr(cm$set("", 1)))
p("keys", cm$keys()); p("raw keys", cache_keys(s)); p("exists", c(cm$exists("abc"), cm$exists("zz"))); p("size", cm$size())
p("exists bad", tr(cm$exists("A")))
p("same as cache_get", cache_get(s, "cachem/abc"))
p("NULL value", tr({cm$set("nul", NULL); list(cm$get("nul"), cm$exists("nul"))}))
p("key_missing value", tr({cm$set("km", cachem::key_missing()); class(cm$get("km"))}))
p("remove", {cm$remove("abc"); cm$exists("abc")}); p("remove missing", tr(cm$remove("nope")))
cache_set(s, "other", 1); cache_set(s, "cachem", 2); cache_set(s, "cachem/UPPER x", 3); cache_set(s, paste0("cachem/", strrep("k", 600)), 4)
p("keys w/ foreign", nchar(cm$keys())); 
p("reset", {cm$reset(); list(cm$keys(), cache_keys(s))})
p("prune", tr(cm$prune())); p("info", tr(cm$info())); p("print", tr(capture.output(print(cm))))
p("prefix empty", tr(as_cachem(s, prefix = ""))); p("prefix opener", tr(as_cachem(s, prefix = "s:"))); p("prefix NA", tr(as_cachem(s, prefix = NA_character_)))
c2 <- as_cachem(s, prefix = "é/"); p("utf prefix", tr({c2$set("a", 1); c(c2$keys(), cache_keys(s, prefix="é"))}))
lat <- "\xe9/"; Encoding(lat) <- "latin1"; c3 <- as_cachem(s, prefix = lat); p("latin1 prefix", tr({c(c3$keys(), c3$get("a"))}))
c4 <- as_cachem(s, prefix = "cachem"); c5 <- as_cachem(s, prefix = "cachem2")
p("prefix overlap", {c4$set("a", 1); c5$set("b", 2); list(c4$keys(), c5$keys())}); p("overlap reset", {c4$reset(); c5$keys()})
p("expire", tr({c6 <- as_cachem(s, prefix = "x/", expire = -1); c6$set("a", 1); list(c6$exists("a"), class(c6$get("a")), c6$keys(), c6$size())}))
p("expire bad", tr(as_cachem(s, expire = "a")))
p("codec bad", tr({c7 <- as_cachem(s, prefix="y/", codec = "rds"); c7$set("a", 1)}))
long <- as_cachem(s, prefix = paste0(strrep("p", 520), "/")); p("long prefix", tr({long$set("a", 1); long$set("b", 2); list(long$get("a"), long$keys(), long$size())}))
# memoise interop
p("memoise pkg", tr({n <- 0; f <- function(x) {n <<- n + 1; x * 2}; mf <- memoise::memoise(f, cache = as_cachem(s, prefix = "m/")); c(mf(2), mf(2), n, memoise::has_cache(mf)(2))}))
p("memoise forget", tr({memoise::forget(mf); mf(2); n}))
p("cachem layered", tr({l <- cachem::cache_layered(cachem::cache_mem(), as_cachem(s, prefix="l/")); l$set("a", 5); l$get("a")}))
p("closed", tr({cache_close(s); cm$get("a")}))

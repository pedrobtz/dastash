source("lib.R")
p <- function(label, x) cat(sprintf("%-28s %s\n", label, substr(paste(capture.output(print(x)), collapse=" / "), 1, 500)))
s <- cache(tempfile("c-"))
long <- strrep("k", 600)
g <- structure(long, class = c("glue", "character"))
a <- structure(long, note = "x")
p("chr attrs kept", attributes(cache_key_chr(structure("a", class="glue", foo=1))))
p("key obj identical?", identical(cache_key(structure("a", foo=1)), cache_key("a")))
cache_set(s, g, "G")
p("get plain after glue set", tr(cache_get(s, long, default = "MISS")))
p("get glue", tr(cache_get(s, g, default = "MISS")))
p("has", cache_has(s, list(long, g)))
cache_set(s, long, "P"); p("after plain set: get glue", tr(cache_get(s, g, default = "MISS")))
p("count", cache_count(s)); p("keys", nchar(cache_keys(s)))
p("delete via plain", {cache_delete(s, long); cache_count(s)})
cache_set(s, a, "A"); p("attr set, plain get", tr(cache_get(s, long, default = "MISS")))
p("keys class", tr(attributes(cache_keys(s))))
p("add plain when attr exists", tr(cache_add(s, long, "second")))
p("incr", tr({cache_incr(s, structure(paste0(long,"c"), note="x")); cache_incr(s, paste0(long,"c"))}))
# short keys w/ attrs: OK?
cache_set(s, structure("short", class="glue"), 1); p("short", tr(cache_get(s, "short", default="MISS")))
# latin1 long key vs utf8
lat <- paste0(strrep("k", 600), "\xe9"); Encoding(lat) <- "latin1"; u <- enc2utf8(lat)
cache_set(s, lat, "L"); p("latin1 long", tr(cache_get(s, u, default="MISS")))
# memoise with long glue arg
p("mget names attr", tr(attributes(names(cache_mget(s, list(g), default=NULL)))))
p("not_found key field", tr(tryCatch(cache_get(s, structure("zz", class="glue")), dazcache_not_found = function(e) attributes(e$key))))
p("cache_key_text w/ attr", attributes(cache_key_text(structure("a", class="glue"))$text))
p("check", tr(cache_check(s)))

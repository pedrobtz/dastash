source("lib.R")
s <- cache(tempfile("c-"))
p <- function(label, x) cat(sprintf("%-28s %s\n", label, paste(capture.output(print(x)), collapse=" / ")))
p("empty key set", tr(cache_set(s, "", 1)))
p("empty key get", tr(cache_get(s, "")))
p("keys", tr(cache_keys(s)))
p("nv key", tr(cache_set(s, numeric_version("1.2"), 1)))
p("pkgver key", tr(cache_key(packageVersion("rlang"))))
# routes
cache_set(s, "a", 1); cache_mset(s, list(b = 2, `{x}` = 3, `s:1` = 4, `~`=5))
p("keys", cache_keys(s))
p("get {x}", tr(cache_get(s, "{x}")))
p("mget", tr(cache_mget(s, c("a","b","{x}","s:1","~"))))
p("has list key", {cache_set(s, list(1,2), "L"); c(cache_has(s, list(1,2)), cache_has(s, list(list(1,2))), cache_has(s, cache_key(list(1,2))))})
p("has chr2 key", {cache_set(s, c("p","q"), "V"); tr(c(cache_has(s, c("p","q")), cache_has(s, list(c("p","q")))))})
p("keys", cache_keys(s))
p("has NULL", tr(cache_has(s, NULL)))
p("set NULL key", tr({cache_set(s, NULL, "n"); cache_get(s, NULL)}))
p("delete NULL", tr(cache_delete(s, NULL)))
p("mget NULL", tr(cache_mget(s, NULL)))
p("has factor", tr({cache_set(s, factor("ff"), 1); c(cache_has(s, factor("ff")), cache_has(s, "ff"), cache_has(s, factor(c("ff","a"))))}))
p("has Date vec", tr({d <- as.Date("2026-01-01")+0:1; cache_set(s, d[1], 1); cache_has(s, d)}))
p("has POSIXct vec", tr({d <- as.POSIXct("2026-01-01", tz="UTC")+0:1; cache_set(s, d[1], 1); cache_has(s, d)}))
p("has difftime vec", tr({d <- as.difftime(1:2, units="hours"); cache_set(s, d[1], 1); cache_has(s, d)}))
p("has i64 vec", tr({d <- bit64::as.integer64(1:2); cache_set(s, d[1], 1); cache_has(s, d)}))
p("has named chr", tr(cache_has(s, c(x="a", y="zz"))))
p("has named int (one key?)", tr({cache_set(s, c(x=1L), 1); list(cache_has(s, c(x=1L)), cache_get(s, c(x=1L), default="MISS"))}))
p("mget dup", tr(cache_mget(s, c("a","a"))))
p("mget default NULL", tr(cache_mget(s, c("a","zz"), default=NULL)))
p("mget names structured", tr(names(cache_mget(s, list(list(1,2), c("p","q"), "a")))))
p("mset dup names", tr({cache_mset(s, list(d=1, d=2)); cache_get(s, "d")}))
p("mset unnamed", tr(cache_mset(s, list(1))))
p("mset partial", tr(cache_mset(s, list(a=1, 2))))
p("mset atomic", tr(cache_mset(s, c(a=1, b=2))))
p("mset df", tr({cache_mset(s, data.frame(col1=1:2, col2=3:4)); cache_get(s,"col1")}))
p("mset NA name", tr(cache_mset(s, setNames(list(1), NA))))
p("mset empty", tr(cache_mset(s, list())))
p("mset NULL value", tr({cache_mset(s, list(nul=NULL)); cache_get(s, "nul")}))
p("set NULL value", tr({cache_set(s, "nul2", NULL); list(cache_get(s, "nul2"), cache_has(s,"nul2"), cache_get(s, "nul2", default="D"))}))
p("pop NULL", tr(cache_pop(s, "nul2")))
p("pop again", tr(cache_pop(s, "nul2", default="gone")))
p("[[", tr({s[["z"]] <- 5; s[["z"]]}))
p("[[ list", tr({s[[list(q=1)]] <- 6; s[[list(q=1)]]}))
p("length", length(s)); p("count", cache_count(s))
al <- tr(as.list(s)); p("as.list names", names(al)); p("as.list n", length(al))
p("keys vs key_text roundtrip", all(vapply(cache_keys(s), function(k) cache_has(s, cache_key_text(k)), NA)))
p("entries", tr(cache_entries(s)[,c("key","bytes","codec","inline","shape")]))
p("info", tr(cache_info(s, list(q=1))))
p("info miss", tr(cache_info(s, "nope")))
p("stats", tr(cache_stats(s)))
print(s)
# long keys
long <- strrep("k", 600); vlong <- strrep("é", 3000)
cache_set(s, long, 1); cache_set(s, vlong, 2); cache_set(s, paste0(long,"x"), 3)
p("long get", tr(c(cache_get(s, long), cache_get(s, vlong), cache_get(s, paste0(long,"x")))))
k <- cache_keys(s); p("long in keys", c(long %in% k, vlong %in% k, sum(startsWith(k, "#"))))
p("prefix long", tr(nchar(cache_keys(s, prefix="kkk"))))
p("prefix é", tr(cache_keys(s, prefix="é")))
p("key_text of #", tr(cache_get(s, cache_key_text(k[startsWith(k,"#")][1]))))
p("entries key long", tr(nchar(cache_entries(s, prefix="k")$key)))
p("info long", tr(nchar(cache_info(s, vlong)$key)))
p("delete long", tr({cache_delete(s, c(long, vlong)); cache_has(s, c(long, vlong, paste0(long,"x")))}))

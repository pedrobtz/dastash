source("lib.R")
p <- function(label, x) cat(sprintf("%-28s %s\n", label, substr(paste(capture.output(print(x)), collapse=" / "), 1, 500)))
s <- cache(tempfile("c-"))
u <- rawToChar(as.raw(c(0x63,0x61,0x66,0xc3,0xa9)))  # "café" as a script parsed in this locale gives it: unmarked
p("locale/enc", c(Sys.getlocale("LC_CTYPE"), Encoding(u)))
cache_set(s, u, 1); cache_set(s, paste0(u, "/x"), 2)
p("get", cache_get(s, u)); p("n keys", length(cache_keys(s)))
p("keys prefix", length(cache_keys(s, prefix = u)))
p("entries prefix", nrow(cache_entries(s, prefix = u)))
p("keys start", length(cache_keys(s, start = u)))
m <- cache_memoise(function(x) x, s, name = u); m(1)
p("memo stored", length(cache_keys(s))); cache_forget_all(m); p("after forget_all", length(cache_keys(s)))
cm <- as_cachem(s, prefix = paste0(u, "-c/")); cm$set("a", 1)
p("cachem get/exists", c(cm$get("a"), cm$exists("a"))); p("cachem keys/size", list(cm$keys(), cm$size())); cm$reset(); p("after reset exists", cm$exists("a"))
cache_evict(s, prefix = u); p("after evict prefix", length(cache_keys(s)))
uu <- u; Encoding(uu) <- "UTF-8"; p("marked prefix", length(cache_keys(s, prefix = uu)))
